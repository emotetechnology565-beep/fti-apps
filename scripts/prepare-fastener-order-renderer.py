"""Bundle the app's renderer and pinned rasterizer for the notification worker."""
from pathlib import Path
import io,json,re,tarfile,urllib.request,hashlib
root=Path(__file__).resolve().parents[1]
out=root/'supabase/functions/operations-whatsapp/fastener-renderer'
out.mkdir(parents=True,exist_ok=True)
for name in ['render','types','hex-render','hex-orthographic']:
    text=(root/f'src/features/drawings/model/{name}.ts').read_text(encoding='utf-8')
    text=re.sub(r"from '(\./[^']+)'",r"from '\1.ts'",text)
    (out/f'{name}.ts').write_text('// Generated by scripts/prepare-fastener-order-renderer.py\n'+text,encoding='utf-8')
assets=out/'assets'
assets.mkdir(exist_ok=True)
url='https://registry.npmjs.org/@resvg/resvg-wasm/-/resvg-wasm-2.6.2.tgz'
if not (assets/'index_bg.wasm').exists():
    with urllib.request.urlopen(url,timeout=30) as response:
        archive=tarfile.open(fileobj=io.BytesIO(response.read()),mode='r:gz')
    for name in ['index.mjs','index.d.ts','index_bg.wasm']:
        (assets/name).write_bytes(archive.extractfile('package/'+name).read())
for name,url in {
    'Roboto.ttf':'https://raw.githubusercontent.com/google/fonts/main/ofl/roboto/Roboto%5Bwdth,wght%5D.ttf',
    'OFL.txt':'https://raw.githubusercontent.com/google/fonts/main/ofl/roboto/OFL.txt',
    'RESVG-LICENSE':'https://raw.githubusercontent.com/thx/resvg-js/v2.6.2/LICENSE',
}.items():
    if not (assets/name).exists():
        with urllib.request.urlopen(url,timeout=30) as response:(assets/name).write_bytes(response.read())
(assets/'manifest.json').write_text(json.dumps({p.name:hashlib.sha256(p.read_bytes()).hexdigest() for p in assets.iterdir() if p.name!='manifest.json'},indent=2)+'\n')
print('Renderer and static assets prepared.')
